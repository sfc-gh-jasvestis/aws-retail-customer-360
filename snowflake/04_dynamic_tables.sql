-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT cohort.ID AS ENTITY_ID, cohort.NAME AS ENTITY_NAME,
       cohort.REGION, cohort.SEGMENT, cohort.RISK_TIER, cohort.STATUS,
       COUNT(*) AS EVENT_COUNT,
       SUM(observation.PURCHASE_COUNT) AS PURCHASE_COUNT,
       SUM(observation.REVENUE_SGD) AS REVENUE_SGD,
       SUM(observation.ISSUE_COUNT) AS ISSUE_COUNT,
       SUM(observation.CHURNED_COUNT) AS CHURNED_COUNT,
       SUM(observation.UNSUBSCRIBED) AS UNSUBSCRIBE_COUNT,
       SUM(observation.TOUCH_DUE) AS TOUCH_DUE,
       SUM(observation.TOUCH_DONE) AS TOUCH_DONE,
       100.0 * (SUM(observation.PURCHASE_COUNT) - SUM(observation.ISSUE_COUNT)) / NULLIF(SUM(observation.PURCHASE_COUNT), 0) AS CLEAN_PURCHASE_PCT,
       100.0 * SUM(observation.CHURNED_COUNT) / NULLIF(SUM(observation.ISSUE_COUNT), 0) AS ISSUE_CHURN_PCT,
       100.0 * SUM(observation.TOUCH_DONE) / NULLIF(SUM(observation.TOUCH_DUE), 0) AS TOUCH_PCT,
       AVG(observation.RETURN_RATE_PCT) AS AVG_RETURN_RATE_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.COHORT_DAILY observation
JOIN RAW.COHORTS cohort ON cohort.ID = observation.ENTITY_ID
GROUP BY cohort.ID, cohort.NAME, cohort.REGION, cohort.SEGMENT, cohort.RISK_TIER, cohort.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(PURCHASE_COUNT) AS PURCHASE_COUNT, SUM(REVENUE_SGD) AS REVENUE_SGD,
       SUM(ISSUE_COUNT) AS ISSUE_COUNT, SUM(CHURNED_COUNT) AS CHURNED_COUNT,
       100.0 * SUM(CHURNED_COUNT) / NULLIF(SUM(ISSUE_COUNT), 0) AS ISSUE_CHURN_PCT
FROM RAW.COHORT_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.ISSUE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT ISSUE_TYPE, SUM(ISSUE_COUNT) AS ISSUE_COUNT,
       SUM(CHURNED_COUNT) AS CHURNED_COUNT,
       SUM(UNSUBSCRIBED) AS UNSUBSCRIBE_COUNT,
       SUM(REVENUE_SGD) AS EXPOSED_REVENUE_SGD,
       100.0 * SUM(CHURNED_COUNT) / NULLIF(SUM(ISSUE_COUNT), 0) AS ISSUE_CHURN_PCT
FROM RAW.COHORT_DAILY
WHERE ISSUE_COUNT > 0
GROUP BY ISSUE_TYPE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(PURCHASE_COUNT) AS ORDERS, SUM(ISSUE_COUNT) AS ISSUES,
         SUM(CHURNED_COUNT) AS CHURNED, SUM(UNSUBSCRIBED) AS BREACHES, SUM(REVENUE_SGD) AS REVENUE_SGD,
         SUM(TOUCH_DUE) AS TOUCH_DUE, SUM(TOUCH_DONE) AS TOUCH_DONE,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.COHORT_DAILY
), book AS (SELECT COUNT(*) AS COHORT_COUNT FROM RAW.COHORTS),
documents AS (
  SELECT 100.0 * SUM(LEAST(ON_FILE_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT,
         SUM(PENDING_QTY) AS PENDING
  FROM RAW.PROFILE_FIELDS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Issue-Free Purchase Rate' AS TITLE,
         100.0 * (ORDERS - ISSUES) / NULLIF(ORDERS, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Service Issues Raised', ISSUES, '' FROM observations
  UNION ALL SELECT 3, 'Churned Members', CHURNED, '' FROM observations
  UNION ALL SELECT 4, 'Issue Churn Rate', 100.0 * CHURNED / NULLIF(ISSUES, 0), '%' FROM observations
  UNION ALL SELECT 5, 'Unsubscribes', BREACHES, '' FROM observations
  UNION ALL SELECT 6, 'Revenue (SGD M)', REVENUE_SGD / 1e6, '' FROM observations
  UNION ALL SELECT 7, 'Purchases Made', ORDERS, '' FROM observations
  UNION ALL SELECT 8, 'CRM Touch Compliance', 100.0 * TOUCH_DONE / NULLIF(TOUCH_DUE, 0), '%' FROM observations
  UNION ALL SELECT 9, 'Cohorts Monitored', COHORT_COUNT, '' FROM book
  UNION ALL SELECT 10, 'Profile Completeness', COVERAGE_PCT, '%' FROM documents
  UNION ALL SELECT 11, 'Profile Fields Pending', PENDING, '' FROM documents
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                WHEN metrics.SORT_ORDER = 1 THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 2), '990.00'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.ISSUE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
